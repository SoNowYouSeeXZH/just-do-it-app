/** 从词库中获取今日成语（基于日期种子，保证每天相同） */
export function getTodayIdiom(): string {
  const today = new Date();
  const seed = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  const index = seed % IDIOM_LIST.length;
  return IDIOM_LIST[index];
}

/** 检查输入是否在词库中 */
export function isValidIdiom(input: string): boolean {
  return IDIOM_LIST.includes(input);
}

/** 检查输入格式是否合法（4个汉字） */
export function isValidFormat(input: string): boolean {
  return /^[\u4e00-\u9fa5]{4}$/.test(input);
}
